#!/bin/sh
# Проверка состояния контейнера копирования.
#
# Смысл проверки: сделать молчаливый отказ заметным. Контейнер, который жив,
# но перестал снимать копии (недоступна база, кончилось место, сломался
# скрипт), из `docker compose ps` выглядел бы полностью исправным. Здесь он
# переходит в unhealthy, и отсутствие копий видно тем же способом, что и
# падение приложения.
set -eu

BACKUP_DIR="${BACKUP_DIR:-/backups}"
# 25 часов, а не 24: суточный график всегда слегка плавает (перезапуск стенда,
# долгий дамп), и ровно суточный порог давал бы ложные срабатывания.
MAX_AGE_HOURS="${BACKUP_MAX_AGE_HOURS:-25}"

marker="${BACKUP_DIR}/last-success"

if [ ! -f "$marker" ]; then
    echo "успешных копий ещё не было"
    exit 1
fi

# Архив обязан лежать рядом с отметкой: отметка без файла — это копия,
# удалённая мимо ротации, а не работающее копирование.
if [ ! -s "${BACKUP_DIR}/latest.dump" ]; then
    echo "отметка об успехе есть, а файла последней копии нет"
    exit 1
fi

age=$(( $(date -u +%s) - $(cut -d' ' -f1 "$marker") ))
if [ "$age" -gt $(( MAX_AGE_HOURS * 3600 )) ]; then
    echo "последняя копия снята $(( age / 3600 )) ч назад, порог ${MAX_AGE_HOURS} ч"
    exit 1
fi

echo "последняя копия снята $(( age / 60 )) мин назад"
