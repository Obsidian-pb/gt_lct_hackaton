#!/bin/sh
# Планировщик суточных копий: бесконечный цикл «снять копию — доспать до
# следующего срока».
#
# Почему не crond, который есть в busybox: ему нужен свой каталог crontabs
# внутри контейнера (а контейнер поднят только для чтения) и он пишет в
# syslog, которого в контейнере нет, — то есть сбой копирования оказался бы
# не виден в `docker compose logs`. Цикл на sh короче, расписание видно прямо
# в переменной окружения, а вывод уходит в журнал контейнера.
set -u

SCRIPT_DIR="$(dirname "$0")"
BACKUP_TIME="${BACKUP_TIME:-00:30}"
# Через сколько повторить попытку после неудачи, не дожидаясь следующих суток.
RETRY_SECONDS=3600

log() {
    echo "[scheduler] $(date -u '+%Y-%m-%d %H:%M:%SZ') $*"
}

nozero() {
    # «09» без обрезки ведущего нуля разбирается как восьмеричное число.
    n="${1#0}"
    echo "${n:-0}"
}

wait_for_schema() {
    # На первом развёртывании контейнер копирования поднимается одновременно
    # с приложением, которое ещё только накатывает миграции. Дамп пустой базы
    # копией не является, и проверка в backup.sh честно забракует его, поэтому
    # перед первым снимком ждём появления схемы.
    attempt=0
    while [ "$attempt" -lt 60 ]; do
        tables="$(psql --tuples-only --no-align --command="
            SELECT count(*) FROM information_schema.tables WHERE table_schema = 'public'
        " 2>/dev/null || echo 0)"
        [ "${tables:-0}" -gt 0 ] && return 0
        attempt=$(( attempt + 1 ))
        sleep 10
    done
    log "схема за 10 минут не появилась — снимаю копию как есть"
}

hh="${BACKUP_TIME%%:*}"
mm="${BACKUP_TIME##*:}"

log "расписание: ежедневно в ${BACKUP_TIME} UTC, хранить копий: ${BACKUP_KEEP:-14}"

wait_for_schema

# Первую копию снимаем сразу при старте, не дожидаясь ночи: так администратор
# видит работоспособность копирования в момент развёртывания, а не через сутки,
# и у стенда есть снимок состояния на момент выкладки новой версии.
while true; do
    if sh "${SCRIPT_DIR}/backup.sh"; then
        # Время до ближайшего срока считаем арифметикой по часам-минутам-
        # секундам: busybox date не умеет разбирать произвольные даты, а так
        # расчёт не зависит от возможностей образа. Ведущие нули срезаются,
        # иначе «08» уехало бы в восьмеричную систему.
        elapsed=$(( $(nozero "$(date -u +%H)") * 3600 \
                  + $(nozero "$(date -u +%M)") * 60 \
                  + $(nozero "$(date -u +%S)") ))
        target=$(( $(nozero "$hh") * 3600 + $(nozero "$mm") * 60 ))
        delta=$(( target - elapsed ))
        [ "$delta" -le 0 ] && delta=$(( delta + 86400 ))
    else
        # Сбой одной копии не снимает расписание: цикл продолжается, но
        # следующая попытка не через сутки, а через час. Кратковременная
        # недоступность базы не должна стоить суточной копии.
        delta="$RETRY_SECONDS"
        log "копирование не удалось, повтор через час"
    fi

    log "следующая копия через $(( delta / 3600 )) ч $(( delta % 3600 / 60 )) мин"
    sleep "$delta"
done
