"""Заявители для учебных карточек.

Имена подставляются программно, а не языковой моделью: модель на каждый
запрос возвращала одного и того же «Иванова Ивана Ивановича», и в ленте
из двадцати карточек это сразу бросалось в глаза.
"""

from __future__ import annotations

import random

SURNAMES_M = (
    "Иванов Петров Смирнов Кузнецов Соколов Попов Лебедев Козлов Новиков Морозов "
    "Волков Соловьёв Васильев Зайцев Павлов Семёнов Голубев Виноградов Богданов Воробьёв"
).split()

NAMES_M = (
    "Александр Алексей Андрей Дмитрий Сергей Иван Михаил Николай Владимир Олег "
    "Павел Роман Егор Артём Максим Юрий Денис Игорь Константин Тимур"
).split()

PATRONYMICS_M = (
    "Александрович Алексеевич Андреевич Дмитриевич Сергеевич Иванович Михайлович "
    "Николаевич Владимирович Олегович Павлович Романович Егорович Артёмович Юрьевич"
).split()

NAMES_F = (
    "Анна Елена Ольга Наталья Ирина Татьяна Мария Светлана Екатерина Юлия "
    "Марина Людмила Галина Вера Александра Дарья Ксения Полина Валентина Нина"
).split()

PATRONYMICS_F = (
    "Александровна Алексеевна Андреевна Дмитриевна Сергеевна Ивановна Михайловна "
    "Николаевна Владимировна Олеговна Павловна Романовна Егоровна Артёмовна Юрьевна"
).split()

# Коды операторов, реально используемые в Москве.
MOBILE_CODES = ("903", "905", "906", "915", "916", "925", "926", "929", "985", "999")


def random_caller(rng: random.Random | None = None) -> str:
    rng = rng or random.Random()
    if rng.random() < 0.5:
        full = (
            f"{rng.choice(SURNAMES_M)} {rng.choice(NAMES_M)} {rng.choice(PATRONYMICS_M)}"
        )
    else:
        surname = rng.choice(SURNAMES_M)
        # Женские фамилии от тех же основ: Иванов — Иванова.
        surname = surname[:-1] + "ая" if surname.endswith("ий") else surname + "а"
        full = f"{surname} {rng.choice(NAMES_F)} {rng.choice(PATRONYMICS_F)}"

    phone = (
        f"{rng.choice(MOBILE_CODES)}-{rng.randint(100, 999)}-"
        f"{rng.randint(10, 99)}-{rng.randint(10, 99)}"
    )
    return f"{full}, {phone}"
