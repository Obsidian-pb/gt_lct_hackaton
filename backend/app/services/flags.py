"""Признаки опросной карты: как они называются на кнопках АРМ-112.

В классификаторе признак — это подколонка списка оповещения с подписью
вроде «Классификатор СМП (выбран признак Пострадавшие)»; при разборе она
сворачивается в ключ `пострадавшие`. Оператору же показываются кнопки
с формулировками рабочей системы: «Пострадавшие», «Нет доступа /
Заблокированные». Фронт ключи не расшифровывает — названия даёт этот
модуль, чтобы у карточки оператора и разбора ошибок они были одни.

Три признака в АРМ-112 стоят на карточке всегда, независимо от типа
происшествия, — это «глобальные» кнопки. Остальные показываются только
там, где у выбранного правила есть подколонка под них: кнопка «Тоннель»
на пожаре в квартире ничему не учит.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.services.ekp import EKP, Rule


@dataclass(frozen=True)
class FlagInfo:
    key: str
    title: str
    hint: str


# Порядок — как на карточке настоящего АРМ-112 (`TZ/imgs/card_0.png`).
