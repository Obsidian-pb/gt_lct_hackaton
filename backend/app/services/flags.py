def describe(key: str) -> FlagInfo:
    """Название и пояснение признака по ключу.

    Для ключа, которого в словаре нет, название собирается из самого ключа:
    новая редакция классификатора может принести признак, о котором здесь
    ещё не знают, и интерфейс от этого ломаться не должен.
    """
    if key in TITLES:
        title, hint = TITLES[key]
        return FlagInfo(key=key, title=title, hint=hint)
    return FlagInfo(key=key, title=key.replace("_", " ").capitalize(), hint="")


def global_flags() -> list[FlagInfo]:
    """Три кнопки, которые есть на карточке АРМ-112 всегда."""
    return [describe(key) for key in GLOBAL_KEYS]


def flags_for_rule(rule: Rule) -> list[FlagInfo]:
    """Признаки, от которых у этого правила зависит список оповещения.

    Берутся только подколонки, где служба реагирует: признак с «нет
    реагирования» службу не добавляет, и кнопка под него была бы пустой.
    Глобальные не повторяются — они и так на карточке. Порядок —
    порядок служб в классификаторе, чтобы кнопки не прыгали между правилами.
    """
    keys: dict[str, None] = {}
    for n in rule.notifications:
        if n.variant_kind != "flag" or not n.responds:
            continue
        for key in sorted(n.requires_flags):
            if key not in GLOBAL_KEYS:
                keys.setdefault(key)
    return [describe(key) for key in keys]


def known_keys(ekp: EKP) -> frozenset[str]:
    """Все ключи признаков редакции — то, что допустимо прислать в карточке.

    Глобальные входят всегда: кнопки под них показываются независимо от
    того, есть ли у правила такая подколонка.
    """
    keys = set(GLOBAL_KEYS)
    for rule in ekp.all_rules():
        for n in rule.notifications:
            keys.update(n.requires_flags)
    return frozenset(keys)
