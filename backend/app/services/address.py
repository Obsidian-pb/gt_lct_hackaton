"""Разбор адреса происшествия на части.

Карточка Системы-112 хранит адрес не строкой, а по полям: субъект,
населённый пункт, улица, дом, корпус, строение, квартира, подъезд, этаж,
код домофона. От полноты этих полей зависит, найдут ли место силы
реагирования, поэтому в тренажёре адрес проверяется по частям, а не целиком.

Разбирается **только то, что разбирается надёжно**. Настоящие вызовы часто
описательные: «напротив Большого Нижнего пруда», «МКАД внутр. сторона, 1 км
не доезжая до съезда», «№ дома неизвестен». Вытягивать из такого улицу и дом
значит придумывать эталон, а неверный эталон учит неправильному. Всё,
что не распозналось, остаётся описательной частью — в рабочей карточке она
тоже есть и заполняется словами заявителя.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

# Части адреса в порядке от общего к частному — в этом же порядке они
# показываются обучающемуся и перечисляются в замечаниях.
PARTS: tuple[tuple[str, str], ...] = (
    ("subject", "субъект"),
    ("settlement", "населённый пункт"),
    ("street", "улица"),
    ("house", "дом"),
    ("building", "корпус"),
    ("structure", "строение"),
    ("flat", "квартира"),
    ("entrance", "подъезд"),
    ("floor", "этаж"),
    ("intercom", "код домофона"),
)

# Без субъекта и населённого пункта выезжать некуда: силы не поймут, чей
# это адрес вообще. Без улицы и дома — не найдут место в городе.
CRITICAL_PARTS = ("subject", "settlement", "street", "house")

# Субъекты, встречающиеся в учебных вызовах. Список закрытый: угадывать
# регион по обрывку названия опаснее, чем оставить поле пустым.
SUBJECTS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("Москва", ("москва", "зеленоград", "мкад", "г. москва")),
    ("Московская область", ("московская обл", "московская область", "мо,", "мо.", "мо ")),
    ("Тульская область", ("тульская обл",)),
    ("Рязанская область", ("рязанская обл", "рязань")),
    ("Владимирская область", ("владимирская обл",)),
    ("Волгоградская область", ("волгоградская обл",)),
)

# Названия улиц в русском адресе пишутся и до, и после родового слова:
# «ул. Берзарина», но «Коломенская набережная». Поэтому два выражения.
# Нечувствительность к регистру распространяется только на родовое слово:
# если применить её ко всему выражению, требование заглавной буквы в названии
# перестаёт работать, и «проезд д 16» разбирается как улица «д 16».
STREET_PREFIX = re.compile(
    r"(?:^|[,.]\s*|\s)(?i:ул|улица|пр-т|проспект|пер|переулок|ш|шоссе|"
    r"наб|набережная|б-р|бульвар|проезд|аллея|тупик|площадь|пл)\.?\s+"
    r"([А-ЯЁ][^,;]{1,60}?)(?=\s*(?:,|;|$|\sдом\b|\sд\.|\sд\s|\sкорп|\sстр))"
)
STREET_SUFFIX = re.compile(
    r"(?:^|,\s*)([А-ЯЁ][^,;]{2,50}?\s+(?:набережная|бульвар|проезд|шоссе|аллея|площадь))"
    r"(?=\s*(?:,|;|$|\sдом\b|\sд\.|\sд\s))",
)

# Границы слова обязательны: без них «д» находится в конце «Зеленоград»,
# и «Зеленоград 9 микрорайон» превращается в дом номер 9.
NUMBERED = {
    "house": r"\b(?:дом|д)\b\.?\s*№?\s*([0-9]+[А-Яа-яЁё]?(?:/[0-9]+)?)",
    "building": r"\b(?:корп|корпус|к)\b\.?\s*([0-9]+[А-Яа-яЁё]?)",
    "structure": r"\b(?:стр|строение)\b\.?\s*([0-9]+[А-Яа-яЁё]?)",
    "flat": r"\b(?:кв|квартира)\b\.?\s*([0-9]+[А-Яа-яЁё]?)",
    "entrance": r"\b(?:под|подъезд)\b\.?\s*([0-9]+)",
    "floor": r"\b(?:эт|этаж)\b\.?\s*([0-9]+)",
    "intercom": r"\b(?:код|домофон)\b\s*(?:домофона)?\s*[№-]?\s*([0-9]+[А-Яа-яЁё]?)",
}

SETTLEMENT = re.compile(
    r"(?:^|,\s*)(?:г\.|город|пос\.|посёлок|поселок|дер\.|деревня|с\.|село|"
    r"городской округ|мкр\.?|микрорайон)\s*([А-ЯЁ][А-Яа-яЁё-]{2,30})",
)


TITLES = dict(PARTS)


@dataclass(frozen=True)
class AddressCheck:
    """Чего не хватает в записанном адресе и что записано неверно.

    Незаполненные части хранятся ключами, а не названиями: по ключу
    определяется, критична ли потеря, а название нужно только для показа.
    Смешение этих двух вещей уже давало ошибку — критичность проверялась
    по русскому названию и не срабатывала никогда.
    """

    missing: tuple[str, ...] = ()
    wrong: tuple[str, ...] = ()

    @property
    def critical_missing(self) -> tuple[str, ...]:
        return tuple(p for p in self.missing if p in CRITICAL_PARTS)

    @staticmethod
    def titles(keys: tuple[str, ...]) -> list[str]:
        return [TITLES.get(key, key) for key in keys]

    @property
    def ok(self) -> bool:
        return not self.missing and not self.wrong


def _subject_of(text: str) -> str | None:
    lowered = text.lower().replace("ё", "е")
    for name, marks in SUBJECTS:
        if any(mark.replace("ё", "е") in lowered for mark in marks):
            return name
    return None


def parse(text: str) -> dict[str, str]:
    """Выделяет из строки адреса то, что распознаётся надёжно."""
    parts: dict[str, str] = {}
    if not text or not text.strip():
        return parts

    if subject := _subject_of(text):
        parts["subject"] = subject
        # Москва — город федерального значения: субъект и населённый пункт
        # совпадают, и требовать их по отдельности было бы придиркой.
        if subject == "Москва":
            parts["settlement"] = "Москва"

    if "settlement" not in parts and (found := SETTLEMENT.search(text)):
        parts["settlement"] = found.group(1).strip()
    if "settlement" not in parts and parts.get("subject", "").endswith("область"):
        # «Московская область, Балашиха, …» — название города идёт сразу
        # за субъектом, без родового слова. Берём его, только если это
        # одиночное слово с заглавной буквы: иначе в поле попадёт описание.
        chunks = [c.strip() for c in re.split(r"[,.]", text) if c.strip()]
        for chunk in chunks[1:3]:
            if re.fullmatch(r"[А-ЯЁ][А-Яа-яЁё-]{2,30}", chunk):
                parts["settlement"] = chunk
                break

    if found := STREET_PREFIX.search(text):
        parts["street"] = found.group(1).strip(" .,")
    elif found := STREET_SUFFIX.search(text):
        parts["street"] = found.group(1).strip(" .,")

    for key, pattern in NUMBERED.items():
        if found := re.search(pattern, text, re.IGNORECASE):
            parts[key] = found.group(1).strip()

    return parts


def normalise(value: str) -> str:
    """Приводит значение к виду, в котором его можно сравнивать.

    Регистр, «ё», сокращения и знаки препинания разнятся у каждого, кто
    записывает адрес на слух. Сверять их дословно значит проверять
    аккуратность набора, а не знание адреса.
    """
    text = value.strip().lower().replace("ё", "е")
    text = re.sub(r"\b(ул|улица|дом|д|корп|корпус|к|стр|строение|кв|квартира|"
                  r"под|подъезд|эт|этаж|обл|область|г|город)\b\.?", " ", text)
    return re.sub(r"[^а-я0-9]+", "", text)


def compare(expected: dict[str, str], answer: dict[str, str]) -> AddressCheck:
    """Сверяет записанный обучающимся адрес с эталонным.

    Спрашивается только то, что есть в эталоне: у половины учебных вызовов
    адрес описательный, и требовать от обучающегося квартиру там, где её
    никто не называл, — придирка к пустому месту.
    """
    missing: list[str] = []
    wrong: list[str] = []
    for key, title in PARTS:
        want = (expected.get(key) or "").strip()
        if not want:
            continue
        got = (answer.get(key) or "").strip()
        if not got:
            missing.append(key)
        elif normalise(got) != normalise(want):
            wrong.append(f"{title}: записано «{got}», следовало «{want}»")
    return AddressCheck(tuple(missing), tuple(wrong))
