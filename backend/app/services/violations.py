@dataclass(frozen=True)
class Violation:
    code: str
    detail: str
    # Чем подтверждается: тайминг, номер события, фрагмент комментария.
    evidence: str | None = None
    # Дословный фрагмент речи заявителя, из которого следует эталон:
    # «…дом двадцать один, корпус один…». Никогда не сочиняется —
    # не нашёлся, значит, замечание без цитаты.
    quote: str | None = None

    @property
    def kind(self) -> ViolationKind:
        return kind_of(self.code)


def kind_of(code: str) -> ViolationKind:
    """Описание нарушения по коду из любого режима обучения."""
    if code in CATALOG:
        return CATALOG[code]
    return OPERATOR_CATALOG[code]


