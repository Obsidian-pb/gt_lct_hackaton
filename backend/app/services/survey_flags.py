"""Признаки опросной карты из речи заявителя.

Эталонные признаки нужны, чтобы сверять с ними то, что отметил оператор:
без них верно услышанные пострадавшие считались бы лишним признаком.
В расшифровках билетов признаки названы прямо — «5 пострадавших с различными
травмами», «пострадавших нет», «водитель заблокирован», — и выводятся
из текста по тому же правилу, что и адрес: **только явные упоминания**.
Всё, что требует догадки («наверное, кто-то пострадал»), остаётся
преподавателю: он правит признаки сценария руками.

Выводятся два признака из семнадцати — те, что заявитель называет
словами. Газификация дома, тоннель или объект из перечня — сведения
не из разговора, а из справочников, и из речи их не взять.
"""

from __future__ import annotations

import re

VICTIMS = "пострадавшие"
NO_ACCESS = "нет_доступа"

# Пострадавшие: число или наличие, глагол, состояние человека. Слова
# о крови и травмах — тоже: заявитель редко говорит «пострадавший»,
# он говорит «лежит в крови».
_VICTIMS = re.compile(
    r"(?:\d+|один|одна|двое|трое|четверо|есть|имеются|имеется)\s+пострадавш"
    r"|пострадал[аио]?\b|пострадавш(?:ий|ая|ие)\b|погиб|без\s+сознания|потерял\w*\s+сознание"
    r"|ранен|травм|кров(?:ь|и|ью|отечени)|перелом|ожог|сломал|не\s+дышит|задыха",
    re.IGNORECASE,
)
# Отрицание сильнее упоминания: «пострадавших нет» — это ответ на вопрос
# оператора, а не признак.
_VICTIMS_NEGATED = re.compile(
    r"пострадавших\s+нет|нет\s+пострадавших|без\s+пострадавших|не\s+пострадал"
    r"|обошлось\s+без\s+пострадавших",
    re.IGNORECASE,
)
_NO_ACCESS = re.compile(
    r"заблокирован|не\s+мо(?:гут|жет|гу)\s+выйти|не\s+мо(?:гут|жет|гу)\s+открыть"
    r"|застрял|заперт|нет\s+доступа|не\s+открывается",
    re.IGNORECASE,
)
_NO_ACCESS_NEGATED = re.compile(r"не\s+(?:за)?блокирован", re.IGNORECASE)


def detect(text: str) -> list[str]:
    """Признаки, названные в тексте явно. Порядок — как на карточке АРМ-112."""
    if not text:
        return []
    found: list[str] = []
    if _VICTIMS.search(text) and not _VICTIMS_NEGATED.search(text):
        found.append(VICTIMS)
    if _NO_ACCESS.search(text) and not _NO_ACCESS_NEGATED.search(text):
        found.append(NO_ACCESS)
    return found
