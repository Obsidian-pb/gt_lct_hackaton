"""Пол заявителя по ФИО — чтобы вызов озвучивал голос подходящего пола.

Мужчина, говорящий женским голосом о «моей жене», сбивает обучающегося
сильнее любой помехи на линии. Пол определяется по русскому ФИО без модели:
отчество даёт ответ почти всегда, фамилия и имя — когда отчества нет.
Не определилось — None, и голос выбирается любой.
"""

from __future__ import annotations

import re

MALE, FEMALE = "male", "female"

_FEMALE_NAMES = {
    "анна", "мария", "елена", "ольга", "наталья", "наталия", "ирина", "светлана",
    "татьяна", "екатерина", "юлия", "анастасия", "марина", "людмила", "галина",
    "валентина", "надежда", "любовь", "вера", "нина", "алла", "лариса", "оксана",
    "дарья", "полина", "ксения", "софья", "алина", "виктория", "евгения",
    "александра", "валерия", "кристина", "зоя", "раиса", "тамара", "лидия", "алёна",
    "алена", "яна", "диана", "маргарита", "жанна", "эльвира", "инна", "вероника",
}
_MALE_NAMES = {
    "александр", "алексей", "андрей", "сергей", "дмитрий", "иван", "михаил",
    "николай", "владимир", "евгений", "павел", "максим", "артём", "артем",
    "олег", "игорь", "виктор", "юрий", "константин", "роман", "денис", "антон",
    "илья", "кирилл", "никита", "василий", "пётр", "петр", "фёдор", "федор",
    "григорий", "борис", "анатолий", "валерий", "геннадий", "вадим", "леонид",
    "степан", "тимур", "руслан", "станислав", "ярослав", "егор", "глеб", "марат",
}

_WORD = re.compile(r"[А-ЯЁа-яё-]+")


def detect(caller: str) -> str | None:
    """Пол по строке заявителя из билета: «Иванова Елена Сергеевна, 916…»."""
    words = [w.lower() for w in _WORD.findall(caller or "")]
    if not words:
        return None
    # Отчество — самый надёжный признак.
    for w in words:
        if re.search(r"(овна|евна|ична|инична)$", w):
            return FEMALE
        if re.search(r"(ович|евич|ич)$", w) and len(w) > 5:
            return MALE
    for w in words:
        if w in _FEMALE_NAMES:
            return FEMALE
        if w in _MALE_NAMES:
            return MALE
    # Фамилия: «-ова», «-ина», «-ская» — женская; «-ов», «-ин», «-ский» — мужская.
    first = words[0]
    if re.search(r"(ова|ева|ёва|ина|ына|ская|цкая|ая)$", first):
        return FEMALE
    if re.search(r"(ов|ев|ёв|ин|ын|ский|цкий|ой|ый)$", first):
        return MALE
    return None


# --- Звонящий в тексте вызова -------------------------------------------------
#
# Когда в билете нет имени заявителя, пол ищется в тексте ситуации. Первое
# ФИО там обычно — пострадавший: «Ребёнок 11 лет, Смирнов Илья… вызывает
# мама». Поэтому сначала ищутся указания на звонящего, и только потом — ФИО,
# причём последнее: звонящий называет себя в конце, перед телефоном.

_CALLER_FEMALE = re.compile(
    r"(вызывает|звонит)\s+(мама|мать|жена|супруга|дочь|сестра|бабушка|соседка|сама"
    r"|кассир\w*\s+[^,.]*?ова|администратор\s+[^,.]*?(ова|ина)\b)"
    r"|разбудить\s+мужа|у\s+меня\s+муж|мой\s+муж",
    re.IGNORECASE,
)
_CALLER_MALE = re.compile(
    r"(вызывает|звонит)\s+(папа|отец|муж|супруг|сын|брат|дедушка|сосед|сам|прохожий|очевидец)\b"
    r"|рожает\s+жена|у\s+меня\s+жена|моя\s+жена|заявитель\s+пришел",
    re.IGNORECASE,
)
_FULL_NAME = re.compile(r"[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+(?:вна|вич|ична|ич)\b")


def detect_in_text(text: str) -> str | None:
    """Пол звонящего по тексту вызова, когда имени заявителя в билете нет."""
    if not text:
        return None
    if _CALLER_FEMALE.search(text):
        return FEMALE
    if _CALLER_MALE.search(text):
        return MALE
    # «Вызывает прохожий Петров Илья Владимирович» — после «вызывает» стоит
    # сам звонящий; «вызывает себе» — звонящий и есть названный человек.
    after = re.search(r"(вызывает|звонит)(?!\s+себе)\s+(.{0,80})", text, re.IGNORECASE)
    if after and (found := detect(after.group(2))):
        return found
    names = _FULL_NAME.findall(text)
    if names:
        return detect(names[-1])
    return None
