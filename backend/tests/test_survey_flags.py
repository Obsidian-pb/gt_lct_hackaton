"""Признаки опросной карты из речи заявителя — на текстах экзаменационных билетов."""

import pytest

from app.services.survey_flags import detect


@pytest.mark.parametrize(
    "text",
    [
        "Дерутся 10-15 человек, 5 пострадавших с различными травмами",
        "Горит а/м Тойота, пострадал водитель, 54 года",
        "Лежит мужчина неизвестный, около 50 лет, без сознания",
        "На обочине лежит мужчина в крови. На вид 40 лет.",
        "Женщина выпила не те препараты, потеряла сознание",
    ],
)
def test_пострадавшие_названы_явно(text):
    assert detect(text) == ["пострадавшие"]


@pytest.mark.parametrize(
    "text",
    [
        "Возгорание мусорного контейнера, пострадавших нет",
        "ДТП, два автомобиля, без пострадавших, перекрыта полоса",
        "Горит балкон на 5 этаже, дым, людей не видно",
    ],
)
def test_отрицание_и_молчание_признаком_не_считаются(text):
    """«Пострадавших нет» — ответ на вопрос оператора, а не признак."""
    assert detect(text) == []


def test_нет_доступа():
    assert detect("В машине Ваз красный водитель заблокирован") == ["нет_доступа"]
    assert detect("ДТП, 3 пострадавших в троллейбусе, не блокированы") == ["пострадавшие"]


def test_оба_признака_в_порядке_карточки():
    assert detect("Пострадала женщина, дверь заперта, не могут открыть") == [
        "пострадавшие",
        "нет_доступа",
    ]


def test_пустой_текст():
    assert detect("") == []
